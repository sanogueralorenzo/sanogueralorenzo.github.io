using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace CrestCore.Generator;

/// Emits the Swift read model and its codec. Records become structs, whose
/// fields are variables only in a record a platform builds to send, enums
/// become `Int` enums or option sets, fixed sets become structs of `static let`
/// members, messages Swift sends (intents, queries, engine events) conform to
/// their root's protocol, and messages it receives (changes, rejections,
/// engine commands) become the cases of their root's enum. An `[Observed]`
/// record also becomes the model class the read model keeps for it, and a
/// record that holds a password names none in its text form.
internal static class SwiftEmitter {
    #region Static Variables

    /// The first label of the wire initializer of a record normalized on
    /// construction. Only the generated codec calls it, so the natural labels
    /// stay free for the platform's normalizing initializer.
    public const string WireInitializerLabel = "normalized";

    /// What an observed model's storage for a field adds to the field's name.
    private const string ObservedStorageSuffix = "Storage";

    /// The hand-written protocol each observed model adopts, and the list of
    /// them the read model keeps, whose whole records views must not read.
    private const string ObservedModelProtocol = "ObservedModel";
    private const string ObservedListClass = "ObservedList";

    /// The hand-written protocol each change adopts, which applies it to the
    /// read model and notes what it tells those who follow its batch.
    private const string ChangeProtocol = "CoreChange";

    /// The path segment under which Swift sources are view code.
    private const string ViewDirectory = "/Features/";

    private const string Header = """
        // <auto-generated/>
        // Generated by CrestCore/tools/CrestCore.Generator from the C# contract records. Do not edit.

        import Foundation

        """;

    #endregion

    #region Actions - Contracts

    public static string EmitContracts(ContractSchema schema) {
        ArgumentNullException.ThrowIfNull(schema);
        var equatable = EquatableRecords(schema);
        var code = new StringBuilder(Header);
        code.Append("\n// MARK: - Roots\n");
        foreach (var root in ContractRoot.All.Where(root => root.PlatformSends)) EmitProtocol(code, root);
        foreach (var family in schema.Families) {
            code.Append('\n').Append($"/// The members of `{family.Root}` that derive from the core's `{family.Base!.Name}`.\n");
            code.Append($"protocol {family.Base!.Name}: {family.Root} {{}}\n");
        }
        foreach (var root in ContractRoot.All.Where(root => !root.PlatformSends)) EmitUnion(code, schema, root, equatable);
        code.Append("""

            extension Change {
                /// Applies the change to the read model, as its own `apply(to:)` does.
                @MainActor func apply(to state: CoreState) {
                    switch self {

            """);
        foreach (var member in schema.Members(ContractRoot.Change))
            code.Append($"        case .{Naming.SwiftMember(member.Name)}(let change): change.apply(to: state)\n");
        code.Append("""
                    }
                }

                /// Applies the change to the core's read model and notes in `batch` what it
                /// tells those who follow the batch, as its own `apply(to:in:)` does.
                @MainActor func apply(to core: CrestCore, in batch: inout CoreChangeBatch) {
                    switch self {

            """);
        foreach (var member in schema.Members(ContractRoot.Change))
            code.Append($"        case .{Naming.SwiftMember(member.Name)}(let change): change.apply(to: core, in: &batch)\n");
        code.Append("""
                    }
                }

                /// Notes in `receipts` what the change tells the cloud transport whose intent
                /// it answers, as its own `note(in:)` does.
                func note(in receipts: inout CloudTransportReceipts) {
                    switch self {

            """);
        foreach (var member in schema.Members(ContractRoot.Change))
            code.Append($"        case .{Naming.SwiftMember(member.Name)}(let change): change.note(in: &receipts)\n");
        code.Append("        }\n    }\n}\n");

        var roots = new Dictionary<Type, (ContractRoot Root, ContractMember Member)>();
        foreach (var root in ContractRoot.All)
            foreach (var member in schema.Members(root)) roots[member.Record.Type] = (root, member);
        code.Append("\n// MARK: - Records\n");
        foreach (var record in schema.Records) {
            var conformances = new List<string>();
            bool isSent = roots.TryGetValue(record.Type, out var owner) && owner.Root.PlatformSends;
            if (isSent) conformances.Add(owner.Root.Name);
            // A change applies itself to the read model, through the hand-written protocol.
            if (roots.TryGetValue(record.Type, out var received) && received.Root == ContractRoot.Change)
                conformances.Add(ChangeProtocol);
            conformances.AddRange(schema.Families.Where(family => family.Base!.IsAssignableFrom(record.Type)).Select(family => family.Base!.Name));
            if (record.IsNormalizedOnConstruction) conformances.Add("Hashable");
            else if (equatable.Contains(record.Type)) conformances.Add("Equatable");
            conformances.Add("Sendable");
            if (record.Fields.Any(field => field.Name == "Id")) conformances.Add("Identifiable");
            code.Append('\n').Append($"struct {record.Name}: {string.Join(", ", conformances)} {{\n");
            if (isSent && owner.Root.HasAnswer)
                code.Append($"    typealias Answer = {TypeName(owner.Member.Answer!)}\n\n");
            // A primitive names its type, so a whole-valued double stays a Double.
            foreach (var constant in record.Statics)
                code.Append($"    static let {Local(constant.Name)}{(constant.Type is PrimitiveField ? $": {TypeName(constant.Type)}" : "")} = "
                    + $"{Literal(constant.Type, constant.Value, StaticIndent)}\n");
            if (record.Statics.Count > 0 && record.Wire.Count > 0) code.Append('\n');
            // A record a platform builds to send is edited in place, so its fields are variables.
            string binding = schema.IsBuilt(record.Type) ? "var" : "let";
            foreach (var field in record.Wire)
                code.Append($"    {binding} {Naming.SwiftIdentifier(Naming.SwiftMember(field.Name))}: {TypeName(field.Type, schema, isSent)}\n");
            if (record.IsNormalizedOnConstruction) EmitWireInitializer(code, record);
            foreach (var (text, index) in record.Texts.Select((text, index) => (text, index))) {
                if (record.Fields.Count > 0 || index > 0) code.Append('\n');
                code.Append($"    var {Naming.SwiftIdentifier(Naming.SwiftMember(text.Name))}: LocalizedStringResource {{\n");
                code.Append($"        {RecordTextLiteral(text)}\n    }}\n");
            }
            if (schema.HasSeed(record.Type)) EmitSeed(code, schema, record, equatable);
            code.Append("}\n");
        }

        var secrets = SecretRecords(schema);
        var redacted = schema.Records.Where(record => secrets.Contains(record.Type)).ToList();
        if (redacted.Count > 0) code.Append("\n// MARK: - Redaction\n");
        foreach (var record in redacted) {
            EmitRedaction(code, record.Name, record.Wire);
            if (schema.HasSeed(record.Type)) EmitRedaction(code, $"{record.Name}.Seed", record.Fields);
        }

        if (schema.Enums.Count > 0) code.Append("\n// MARK: - Enums\n");
        foreach (var item in schema.Enums) {
            code.Append('\n');
            if (item.IsFlags) {
                code.Append($"struct {item.Name}: OptionSet, Sendable {{\n    let rawValue: Int\n");
                foreach (var member in item.Members.Where(member => member.Value != 0))
                    code.Append($"    static let {Naming.SwiftIdentifier(Naming.SwiftMember(member.Key))} = {item.Name}(rawValue: {member.Value})\n");
            } else {
                code.Append($"enum {item.Name}: Int, CaseIterable, Sendable {{\n");
                foreach (var member in item.Members)
                    code.Append($"    case {Naming.SwiftIdentifier(Naming.SwiftMember(member.Key))} = {member.Value}\n");
            }
            code.Append("}\n");
        }

        if (schema.Sets.Count > 0) code.Append("\n// MARK: - Fixed sets\n");
        foreach (var set in schema.Sets) EmitSet(code, set);

        var observed = schema.Records.Where(record => record.IsObserved).ToList();
        if (observed.Count > 0) code.Append("\n// MARK: - Observed models\n");
        foreach (var record in observed) EmitModel(code, record, equatable);
        return code.ToString();
    }

    /// A record that holds [Resolved] values, itself or in its fields, has a
    /// seed: its fields alone, with seeds in them, which a platform builds to
    /// send and the core resolves when it reads it. A seed has no resolved
    /// value to read, and a platform builds it field by field, so its fields
    /// are variables. A published record gives its own as `seed`.
    private static void EmitSeed(StringBuilder code, ContractSchema schema, ContractRecord record, HashSet<Type> equatable) {
        if (record.IsNormalizedOnConstruction || record.Fields.Any(field => Naming.SwiftMember(field.Name) == "seed"))
            throw new ContractSchemaException($"{record.Name}: a record with a seed cannot be normalized on construction "
                + "or name a field Seed.");
        var conformances = new List<string>();
        if (equatable.Contains(record.Type)) conformances.Add("Equatable");
        conformances.Add("Sendable");
        if (record.IsIdentified) conformances.Add("Identifiable");
        code.Append('\n').Append($"    /// The fields of a `{record.Name}` alone, as a platform builds one to send. The\n");
        code.Append("    /// core resolves the rest when it reads it.\n");
        code.Append($"    struct Seed: {string.Join(", ", conformances)} {{\n");
        foreach (var field in record.Fields) code.Append($"        var {Local(field.Name)}: {TypeName(field.Type, schema, seeds: true)}\n");
        code.Append("    }\n\n    /// The record's fields alone, as a platform sends it back.\n    var seed: Seed {\n");
        code.Append(Wrapped("        Seed(", ")", [.. record.Fields.Select(field =>
            $"{Naming.SwiftMember(field.Name)}: {SeedValue(field.Type, schema, Local(field.Name))}")])).Append("\n    }\n");
    }

    /// `value`, a field of a published record, with each record in it that
    /// has a seed as that seed.
    private static string SeedValue(FieldType type, ContractSchema schema, string value) => type switch {
        RecordField record when schema.HasSeed(record.Type) => $"{value}.seed",
        ListField { Element: RecordField element } when schema.HasSeed(element.Type) => $"{value}.map(\\.seed)",
        OptionalField { Value: RecordField held } when schema.HasSeed(held.Type) => $"{value}?.seed",
        ListField list when schema.HoldsSeed(list) => $"{value}.map {{ {SeedValue(list.Element, schema, "$0")} }}",
        OptionalField optional when schema.HoldsSeed(optional) => $"{value}.map {{ {SeedValue(optional.Value, schema, "$0")} }}",
        _ => value
    };

    /// A record normalized on construction has no memberwise initializer. The
    /// codec makes it through this one, labeled so that the natural spelling
    /// stays free for the platform's initializer, which normalizes.
    private static void EmitWireInitializer(StringBuilder code, ContractRecord record) {
        var labels = InitializerLabels(record);
        string natural = string.Concat(record.Wire.Select(field => $"{Naming.SwiftMember(field.Name)}:"));
        code.Append('\n').Append("    /// The wire's initializer: the codec's alone, for values the core wrote after\n");
        code.Append($"    /// normalizing them. Anything else makes one with `init({natural})`, which normalizes.\n");
        code.Append(Wrapped("    init(", ")", [.. record.Wire.Select((field, index) =>
            $"{(labels[index] == Naming.SwiftMember(field.Name) ? "" : $"{labels[index]} ")}{Local(field.Name)}: {TypeName(field.Type)}")]));
        code.Append(" {\n");
        foreach (var field in record.Wire) code.Append($"        self.{Local(field.Name)} = {Local(field.Name)}\n");
        code.Append("    }\n");
    }

    /// The labels generated code makes a record with, one per wire field in
    /// order: the fields' own names, except that a record normalized on
    /// construction is made through its wire initializer.
    private static IReadOnlyList<string> InitializerLabels(ContractRecord record) =>
        [.. record.Wire.Select((field, index) =>
            index == 0 && record.IsNormalizedOnConstruction ? WireInitializerLabel : Naming.SwiftMember(field.Name))];

    /// An observed record becomes a main-actor observable class with one
    /// property per field. Each field keeps its value in storage Observation
    /// ignores: its getter registers the read as one of the field, and
    /// `update` stores a value that differs before it announces the change.
    /// SwiftUI can render while a change is announced, so a view rendered
    /// there reads the new value instead of keeping the old one; and an equal
    /// value notifies no observer whatever the Observation runtime does with
    /// equal writes. The identity is fixed.
    private static void EmitModel(StringBuilder code, ContractRecord record, HashSet<Type> equatable) {
        if (!equatable.Contains(record.Type))
            throw new ContractSchemaException($"{record.Name}: an [Observed] record compares its fields, so none may hold an intent or a query.");
        string model = $"{record.Name}Model";
        var labels = InitializerLabels(record);
        var fields = record.Wire.Select((field, index) => (Label: labels[index], Name: Local(field.Name),
            Storage: $"{Naming.SwiftMember(field.Name)}{ObservedStorageSuffix}", Type: TypeName(field.Type),
            IsIdentity: field.Name == ContractRecord.IdentityField)).ToList();
        var observed = fields.Where(field => !field.IsIdentity).ToList();
        code.Append('\n').Append($"/// `{record.Name}` as an object views observe field by field. `update` stores each\n");
        code.Append("/// field that differs before it announces the change, and announces nothing for a\n");
        code.Append("/// field that keeps its value.\n");
        code.Append("@MainActor\n@Observable\n");
        code.Append($"final class {model}: {ObservedModelProtocol}{(record.IsIdentified ? ", Identifiable" : "")} {{\n");
        foreach (var field in fields.Where(field => field.IsIdentity)) code.Append($"    let {field.Name}: {field.Type}\n");
        foreach (var field in observed) {
            code.Append($"    var {field.Name}: {field.Type} {{\n");
            code.Append($"        access(keyPath: \\.{field.Name})\n");
            code.Append($"        return {field.Storage}\n");
            code.Append("    }\n");
        }
        if (observed.Count > 0) code.Append('\n');
        foreach (var field in observed) code.Append($"    @ObservationIgnored private var {field.Storage}: {field.Type}\n");
        code.Append('\n').Append($"    var value: {record.Name} {{\n");
        code.Append(Wrapped($"        {record.Name}(", ")", [.. fields.Select(field => $"{field.Label}: {field.Name}")])).Append('\n');
        code.Append("    }\n");
        code.Append('\n').Append($"    init(_ value: {record.Name}) {{\n");
        foreach (var field in fields) code.Append($"        {(field.IsIdentity ? field.Name : field.Storage)} = value.{field.Name}\n");
        code.Append("    }\n");
        code.Append('\n').Append($"    func update(_ value: {record.Name}) {{\n");
        foreach (var field in fields.Where(field => field.IsIdentity))
            code.Append($"        precondition(value.{field.Name} == {field.Name}, \"A {model} takes only its own {record.Name}'s values.\")\n");
        foreach (var field in observed) {
            code.Append($"        if {field.Storage} != value.{field.Name} {{\n");
            code.Append($"            {field.Storage} = value.{field.Name}\n");
            code.Append($"            withMutation(keyPath: \\.{field.Name}) {{}}\n");
            code.Append("        }\n");
        }
        code.Append("    }\n}\n");
    }

    /// A fixed set becomes a struct with one `static let` per member, built
    /// from the member's wire tag and the literal values of its data. Two
    /// values are equal when they are the same member. An open set's struct has
    /// no tag and a memberwise initializer, and two values are equal when their
    /// names are.
    ///
    /// The member's data lives in one shared `Facts` object, so the struct has
    /// a fixed layout whatever its data holds. A `LocalizedStringResource` has
    /// none, and stored in the struct it left every record that holds the set
    /// sized only at runtime: Swift reserves such values at the top of the
    /// function, so the change decoder's frame outgrew an iPhone's main thread.
    private static void EmitSet(StringBuilder code, ContractSet set) {
        var properties = set.Properties.Select(property => (Name: Local(property.Name), property.Type)).ToList();
        code.Append('\n').Append(set.IsOpen
            ? $"/// The members of the core's `{set.Name}`, which also makes members at runtime. Members are equal when their names are.\n"
            : $"/// The members of the core's `{set.Name}`. A member's wire tag is its index in `all`.\n");
        if (set.CoreOnly.Count > 0)
            code.Append($"/// Core-only behavior, not emitted: {string.Join(", ", set.CoreOnly.Select(name => $"`{name}`"))}.\n");
        code.Append($"struct {set.Name}: Hashable, Sendable {{\n");
        foreach (var kinds in set.Properties.Select(property => property.Type).OfType<KindsField>()) {
            code.Append($"    enum {kinds.Type.Name}: Sendable {{\n");
            foreach (string kind in Enum.GetNames(kinds.Type)) code.Append($"        case {Local(kind)}\n");
            code.Append("    }\n\n");
        }
        foreach (var constant in set.Constants)
            code.Append($"    static let {Local(constant.Name)} = {Literal(constant.Type, constant.Value, MemberIndent)}\n");
        if (set.Constants.Count > 0) code.Append('\n');
        if (!set.IsOpen) code.Append("    let tag: Int\n");
        foreach (var property in properties)
            code.Append($"    var {property.Name}: {TypeName(property.Type)} {{ facts.{property.Name} }}\n");
        if (properties.Count > 0) code.Append("    private let facts: Facts\n");
        string[] tag = set.IsOpen ? [] : ["tag: Int"];
        var parameters = properties.Select(property => $"{property.Name}: {TypeName(property.Type)}").ToList();
        code.Append('\n').Append(Wrapped(set.IsOpen ? "    init(" : "    private init(", ")", [.. tag, .. parameters]));
        code.Append(" {\n");
        if (!set.IsOpen) code.Append("        self.tag = tag\n");
        if (properties.Count > 0)
            code.Append(Wrapped("        facts = Facts(", ")", [.. properties.Select(property => $"{property.Name}: {property.Name}")]))
                .Append('\n');
        code.Append("    }\n\n");
        foreach (var member in set.Members) {
            string[] memberTag = set.IsOpen ? [] : [$"tag: {member.Tag}"];
            code.Append(Wrapped($"    static let {Local(member.Name)} = {set.Name}(", ")", [
                .. memberTag,
                .. properties.Select((property, index) =>
                    $"{property.Name}: {Literal(property.Type, member.Values[index], MemberIndent)}")])).Append('\n');
        }
        code.Append('\n').Append(Wrapped($"    static let all: [{set.Name}] = [", "]", [.. set.Members.Select(member => Local(member.Name))]))
            .Append('\n');
        code.Append('\n').Append($"    static func named(_ name: String?) -> {set.Name}? {{\n        all.first {{ $0.name == name }}\n    }}\n");
        string identity = set.IsOpen ? "name" : "tag";
        code.Append('\n').Append($"    static func == (lhs: {set.Name}, rhs: {set.Name}) -> Bool {{\n        lhs.{identity} == rhs.{identity}\n    }}\n");
        code.Append('\n').Append($"    func hash(into hasher: inout Hasher) {{\n        hasher.combine({identity})\n    }}\n");
        if (properties.Count > 0) {
            code.Append("\n    private final class Facts: Sendable {\n");
            foreach (var property in properties) code.Append($"        let {property.Name}: {TypeName(property.Type)}\n");
            code.Append('\n').Append(Wrapped("        init(", ")", parameters)).Append(" {\n");
            foreach (var property in properties) code.Append($"            self.{property.Name} = {property.Name}\n");
            code.Append("        }\n    }\n");
        }
        code.Append("}\n");
    }

    /// A root the platform sends becomes the protocol its messages conform to,
    /// each encoding itself with its tag; a question also decodes its answer.
    private static void EmitProtocol(StringBuilder code, ContractRoot root) {
        code.Append('\n').Append($"/// {root.SwiftDocumentation}\n");
        code.Append($"protocol {root.Name}: Sendable {{\n");
        if (root.HasAnswer) code.Append("    associatedtype Answer: Sendable\n");
        code.Append($"    func encode{root.Name}(into writer: inout WireWriter)\n");
        if (root.HasAnswer) code.Append("    static func decodeAnswer(from reader: inout WireReader) throws(WireError) -> Answer\n");
        if (root == ContractRoot.PageRequest) {
            code.Append("    /// What WebKit answers, from the pages its binding holds; each request's\n");
            code.Append("    /// own file says how.\n");
            code.Append("    @MainActor func answer(on pages: WebKitEnginePages) -> Answer\n");
        }
        code.Append("}\n");
    }

    /// A root the platform receives becomes an enum with a case per message.
    /// Each text some of its messages carry is read through the enum as an
    /// optional, nil for a message without it.
    private static void EmitUnion(StringBuilder code, ContractSchema schema, ContractRoot root, HashSet<Type> equatable) {
        var members = schema.Members(root);
        bool isEquatable = members.All(member => equatable.Contains(member.Record.Type));
        code.Append('\n').Append($"/// {root.SwiftDocumentation}\n");
        code.Append($"enum {root.Name}: {(isEquatable ? "Equatable, " : "")}{root.SwiftConformances} {{\n");
        foreach (var member in members) code.Append($"    case {Naming.SwiftMember(member.Name)}({member.Name})\n");
        foreach (string name in members.SelectMany(member => member.Record.Texts).Select(text => text.Name).Distinct().Order(StringComparer.Ordinal)) {
            string property = Naming.SwiftIdentifier(Naming.SwiftMember(name));
            var carriers = members.Where(member => member.Record.Texts.Any(text => text.Name == name)).ToList();
            code.Append('\n').Append($"    var {property}: LocalizedStringResource? {{\n        switch self {{\n");
            foreach (var member in carriers)
                code.Append($"        case .{Naming.SwiftMember(member.Name)}(let value): value.{property}\n");
            if (carriers.Count < members.Count) code.Append("        default: nil\n");
            code.Append("        }\n    }\n");
        }
        foreach (var (family, field) in schema.Facts(root)) {
            string property = Naming.SwiftIdentifier(Naming.SwiftMember(field.Name));
            var others = members.Where(member => !family.IsAssignableFrom(member.Record.Type)).ToList();
            code.Append('\n').Append($"    /// The `{field.Name}` every member of the core's `{family.Name}` carries")
                .Append(others.Count > 0 ? ", or nil for any other.\n" : ".\n");
            code.Append($"    var {property}: {TypeName(field.Type)}{(others.Count > 0 ? "?" : "")} {{\n        switch self {{\n");
            if (others.Count > 0)
                code.Append($"        case {string.Join(", ", others.Select(member => $".{Naming.SwiftMember(member.Name)}"))}: nil\n");
            foreach (var member in members.Where(member => family.IsAssignableFrom(member.Record.Type)))
                code.Append($"        case .{Naming.SwiftMember(member.Name)}(let value): value.{property}\n");
            code.Append("        }\n    }\n");
        }
        code.Append("}\n");
    }

    /// A record that holds a password, itself or through its fields, names none
    /// when it is printed, logged or dumped: its text shows its name and each
    /// list's count and nothing else of its values, and its mirror has no
    /// children.
    private static void EmitRedaction(StringBuilder code, string name, IReadOnlyList<ContractField> fields) {
        string shown = string.Join(", ", fields.Select(field =>
            $"{Naming.SwiftMember(field.Name)}: {(field.Type is ListField ? $"\\({Local(field.Name)}.count)" : "<redacted>")}"));
        code.Append('\n').Append("/// Holds a password, itself or in its fields, so its text names none: it shows\n");
        code.Append("/// each list's count and nothing else of its values.\n");
        code.Append($"extension {name}: CustomStringConvertible, CustomDebugStringConvertible, CustomReflectable {{\n");
        code.Append($"    var description: String {{\n        \"{name}({shown})\"\n    }}\n\n");
        code.Append("    var debugDescription: String { description }\n");
        code.Append("    var customMirror: Mirror { Mirror(self, children: [], displayStyle: .struct) }\n}\n");
    }

    /// Every record marked `[HoldsSecrets]`, and every record that holds one
    /// through a field, a list, an optional, another record or a union one of
    /// whose members holds one.
    private static HashSet<Type> SecretRecords(ContractSchema schema) {
        var secrets = schema.Records.Where(record => record.HoldsSecrets).Select(record => record.Type).ToHashSet();
        bool changed = true;
        while (changed) {
            changed = false;
            foreach (var record in schema.Records.Where(record => !secrets.Contains(record.Type)))
                if (record.Wire.Any(field => HoldsSecrets(field.Type, secrets, schema))) changed |= secrets.Add(record.Type);
        }
        return secrets;
    }

    private static bool HoldsSecrets(FieldType type, HashSet<Type> secrets, ContractSchema schema) => type switch {
        RecordField record => secrets.Contains(record.Type),
        RootField union => schema.Members(union).Any(member => secrets.Contains(member.Record.Type)),
        ListField list => HoldsSecrets(list.Element, secrets, schema),
        OptionalField optional => HoldsSecrets(optional.Value, secrets, schema),
        _ => false
    };

    /// A record's text as a `LocalizedStringResource`. Its argument, when it
    /// has one, is the record's own field, interpolated where the text spells
    /// `%lld`, so every value shares one catalog key.
    private static string RecordTextLiteral(RecordText text) {
        string literal = StringLiteral(text.Text);
        if (text.Argument is { } argument)
            literal = literal.Replace("%lld", $"\\({Naming.SwiftIdentifier(Naming.SwiftMember(argument))})", StringComparison.Ordinal);
        return text.Comment is { } comment
            ? $"LocalizedStringResource({literal}, comment: {StringLiteral(comment)})"
            : $"LocalizedStringResource({literal})";
    }

    /// A record is Equatable unless it holds, directly or through its fields,
    /// an intent or a query existential.
    private static HashSet<Type> EquatableRecords(ContractSchema schema) {
        var records = schema.Records.ToDictionary(record => record.Type);
        var excluded = new HashSet<Type>();
        bool changed = true;
        while (changed) {
            changed = false;
            foreach (var record in records.Values.Where(record => !excluded.Contains(record.Type)))
                if (record.Wire.Any(field => !IsEquatable(field.Type, excluded, schema))) changed |= excluded.Add(record.Type);
        }
        return [.. records.Keys.Where(type => !excluded.Contains(type))];
    }

    private static bool IsEquatable(FieldType type, HashSet<Type> excluded, ContractSchema schema) => type switch {
        RecordField record => !excluded.Contains(record.Type),
        RootField { Root.PlatformSends: true } => false,
        RootField root => schema.Members(root.Root).All(member => !excluded.Contains(member.Record.Type)),
        ListField list => IsEquatable(list.Element, excluded, schema),
        OptionalField optional => IsEquatable(optional.Value, excluded, schema),
        _ => true
    };

