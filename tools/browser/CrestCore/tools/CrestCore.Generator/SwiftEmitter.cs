    #region Actions - Codec

    public static string EmitCodec(ContractSchema schema) {
        ArgumentNullException.ThrowIfNull(schema);
        var code = new StringBuilder(Header);
        code.Append('\n').Append("/// The wire codec's schema identity and the unions Swift decodes.\n");
        code.Append("enum CoreCodec {\n");
        code.Append("    /// SHA-256 of the canonical contract schema. The core refuses any other.\n");
        code.Append("    static let fingerprint: [UInt8] = [\n        ");
        code.Append(string.Join(", ", schema.Fingerprint.Select(value => $"0x{value:x2}"))).Append("\n    ]\n");
        code.Append("    /// SHA-256 of the engine contract alone, which an engine binding registers with.\n");
        code.Append("    static let engineFingerprint: [UInt8] = [\n        ");
        code.Append(string.Join(", ", schema.EngineFingerprint.Select(value => $"0x{value:x2}"))).Append("\n    ]\n");
        foreach (var root in ContractRoot.All.Where(root => root.PlatformSends)) {
            code.Append('\n').Append($"    static func decode{root}(from reader: inout WireReader) throws(WireError) -> any {root} {{\n");
            code.Append("        let tag = try reader.readTag()\n        switch tag {\n");
            foreach (var member in schema.Members(root))
                code.Append($"        case {member.Tag}: return try {member.Name}(from: &reader)\n");
            code.Append($"        default: throw WireError.malformed(\"Unknown {root} tag \\(tag)\")\n        }}\n    }}\n");
        }
        foreach (var narrowed in schema.Bases) {
            string name = narrowed.Base!.Name;
            code.Append('\n').Append($"    static func decode{name}(from reader: inout WireReader) throws(WireError) -> any {name} {{\n");
            code.Append("        let tag = try reader.readTag()\n        switch tag {\n");
            foreach (var member in schema.Members(narrowed))
                code.Append($"        case {member.Tag}: return try {member.Name}(from: &reader)\n");
            code.Append($"        default: throw WireError.malformed(\"{narrowed.Root} tag \\(tag) is not a {name}\")\n        }}\n    }}\n");
        }
        code.Append("}\n");

        foreach (var root in ContractRoot.All.Where(root => !root.PlatformSends)) {
            var members = schema.Members(root);
            code.Append('\n').Append($"extension {root} {{\n");
            code.Append("    init(from reader: inout WireReader) throws(WireError) {\n");
            code.Append("        let tag = try reader.readTag()\n        switch tag {\n");
            foreach (var member in members)
                code.Append($"        case {member.Tag}: self = .{Naming.SwiftMember(member.Name)}(try {member.Name}(from: &reader))\n");
            code.Append($"        default: throw WireError.malformed(\"Unknown {root} tag \\(tag)\")\n        }}\n    }}\n\n");
            code.Append("    func encode(into writer: inout WireWriter) {\n        switch self {\n");
            foreach (var member in members) {
                code.Append($"        case .{Naming.SwiftMember(member.Name)}(let value):\n");
                code.Append($"            writer.writeTag({member.Tag})\n            value.encode(into: &writer)\n");
            }
            code.Append("        }\n    }\n}\n");
        }

        var tags = new Dictionary<Type, (ContractRoot Root, ContractMember Member)>();
        foreach (var root in ContractRoot.All.Where(root => root.PlatformSends))
            foreach (var member in schema.Members(root)) tags[member.Record.Type] = (root, member);
        foreach (var record in schema.Records) {
            code.Append('\n').Append($"extension {record.Name} {{\n");
            code.Append("    init(from reader: inout WireReader) throws(WireError) {\n");
            var lines = new List<string>();
            bool isSent = tags.ContainsKey(record.Type);
            foreach (var field in record.Wire) Decode(field.Type, Local(field.Name), lines, "        ", schema, isSent);
            foreach (var line in lines) code.Append(line).Append('\n');
            var labels = InitializerLabels(record);
            code.Append("        self.init(");
            code.Append(string.Join(", ", record.Wire.Select((field, index) => $"{labels[index]}: {Local(field.Name)}")));
            code.Append(")\n    }\n\n");
            code.Append("    func encode(into writer: inout WireWriter) {\n");
            foreach (var field in record.Wire)
                code.Append(Encode(field.Type, Naming.SwiftIdentifier(Naming.SwiftMember(field.Name)), "        ", 0));
            code.Append("    }\n");
            if (tags.TryGetValue(record.Type, out var owner)) {
                code.Append('\n').Append($"    func encode{owner.Root}(into writer: inout WireWriter) {{\n");
                code.Append($"        writer.writeTag({owner.Member.Tag})\n        encode(into: &writer)\n    }}\n");
                if (owner.Root.HasAnswer) {
                    var answer = new List<string>();
                    Decode(owner.Member.Answer!, "answer", answer, "        ");
                    code.Append('\n').Append($"    static func decodeAnswer(from reader: inout WireReader) throws(WireError) -> {TypeName(owner.Member.Answer!)} {{\n");
                    foreach (var line in answer) code.Append(line).Append('\n');
                    code.Append("        return answer\n    }\n");
                }
            }
            code.Append("}\n");
            if (schema.HasSeed(record.Type)) EmitSeedCodec(code, schema, record);
        }

        foreach (var item in schema.Enums) {
            code.Append('\n').Append($"extension {item.Name} {{\n");
            code.Append("    init(from reader: inout WireReader) throws(WireError) {\n");
            code.Append("        let rawValue = try reader.readEnum()\n");
            if (item.IsFlags) {
                int mask = item.Members.Aggregate(0, (bits, member) => bits | member.Value);
                code.Append($"        guard rawValue & ~{mask} == 0 else {{ throw WireError.malformed(\"Unknown {item.Name} \\(rawValue)\") }}\n");
                code.Append("        self.init(rawValue: rawValue)\n");
            } else {
                code.Append($"        guard let value = {item.Name}(rawValue: rawValue) else {{\n");
                code.Append($"            throw WireError.malformed(\"Unknown {item.Name} \\(rawValue)\")\n        }}\n");
                code.Append("        self = value\n");
            }
            code.Append("    }\n\n    func encode(into writer: inout WireWriter) {\n        writer.writeEnum(rawValue)\n    }\n}\n");
        }

        foreach (var set in schema.Sets.Where(set => !set.IsOpen)) {
            code.Append('\n').Append($"extension {set.Name} {{\n");
            code.Append("    init(from reader: inout WireReader) throws(WireError) {\n");
            code.Append("        let tag = try reader.readEnum()\n");
            code.Append($"        guard Self.all.indices.contains(tag) else {{\n            throw WireError.malformed(\"Unknown {set.Name} \\(tag)\")\n        }}\n");
            code.Append("        self = Self.all[tag]\n");
            code.Append("    }\n\n    func encode(into writer: inout WireWriter) {\n        writer.writeEnum(tag)\n    }\n}\n");
        }
        return code.ToString();
    }

    /// A seed crosses the wire as its fields alone, with seeds in them.
    private static void EmitSeedCodec(StringBuilder code, ContractSchema schema, ContractRecord record) {
        code.Append('\n').Append($"extension {record.Name}.Seed {{\n");
        code.Append("    init(from reader: inout WireReader) throws(WireError) {\n");
        var lines = new List<string>();
        foreach (var field in record.Fields) Decode(field.Type, Local(field.Name), lines, "        ", schema, seeds: true);
        foreach (var line in lines) code.Append(line).Append('\n');
        code.Append("        self.init(");
        code.Append(string.Join(", ", record.Fields.Select(field => $"{Naming.SwiftMember(field.Name)}: {Local(field.Name)}")));
        code.Append(")\n    }\n\n    func encode(into writer: inout WireWriter) {\n");
        foreach (var field in record.Fields)
            code.Append(Encode(field.Type, Naming.SwiftIdentifier(Naming.SwiftMember(field.Name)), "        ", 0));
        code.Append("    }\n}\n");
    }

