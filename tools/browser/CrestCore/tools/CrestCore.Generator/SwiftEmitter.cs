    #region Actions - Whole-record reads in views

    /// Each read in a view source of a read-model object's whole record, its
    /// `value`, or of a list's `values`, as `path:line` and what to read
    /// instead. Such a read observes every field, so a change to any of them
    /// redraws the view. A view source is one under a `Features` directory.
    /// The read-model objects are the observed models this generator emits,
    /// the classes that adopt `ObservedModel` by hand and `ObservedList`; a
    /// read is found through a name the source declares as one of them, a
    /// member any source declares as a list or a map of them, a list's
    /// `model(_:)` or a key path over its `models`. A line's `//` comment is
    /// not code, so it is not searched.
    public static IReadOnlyList<string> WholeRecordReads(ContractSchema schema, IReadOnlyList<(string Path, string Text)> sources) {
        ArgumentNullException.ThrowIfNull(schema);
        ArgumentNullException.ThrowIfNull(sources);
        var code = sources.Select(source => (source.Path, Code: string.Join('\n', source.Text.Split('\n')
            .Select(line => line.Split("//", 2)[0])))).ToList();
        var adopter = new Regex($@"\bclass\s+(?<name>\w+)\s*(?:<[^>{{]*>)?\s*:[^{{]*\b{ObservedModelProtocol}\b",
            RegexOptions.CultureInvariant);
        var types = schema.Records.Where(record => record.IsObserved).Select(record => $"{record.Name}Model")
            .Concat(code.SelectMany(source => adopter.Matches(source.Code).Select(match => match.Groups["name"].Value)))
            .Append(ObservedListClass).ToHashSet(StringComparer.Ordinal);
        string typeNames = string.Join("|", types.Order(StringComparer.Ordinal).Select(Regex.Escape));
        var listMember = new Regex($@"\b(?:let|var)\s+(?<name>\w+)\s*:\s*{ObservedListClass}\s*<", RegexOptions.CultureInvariant);
        var mapMember = new Regex($@"\b(?:let|var)\s+(?<name>\w+)\s*:\s*\[\s*\w+\s*:\s*(?:{typeNames})\s*\]",
            RegexOptions.CultureInvariant);
        string lists = Alternatives(code.SelectMany(source => listMember.Matches(source.Code)));
        string maps = Alternatives(code.SelectMany(source => mapMember.Matches(source.Code)));
        var declared = new Regex($@"\b(?<name>\w+)\s*:\s*(?:{typeNames})\b", RegexOptions.CultureInvariant);
        var shapes = new List<string> {
            @"\.model\s*\([^()\n]*\)\s*[?!]?\s*\.value\b",
            @"\.models\s*\.\s*\w+\s*\(\s*\\\.value\b"
        };
        if (lists.Length > 0) shapes.Add($@"\.(?:{lists})\s*[?!]?\s*\.values\b");
        if (maps.Length > 0) shapes.Add($@"\.(?:{maps})\s*\[[^\]\n]*\]\s*[?!]?\s*\.value\b");
        var reads = new List<string>();
        foreach (var (path, text) in code.Where(source => source.Path.Contains(ViewDirectory, StringComparison.Ordinal))) {
            string names = Alternatives(declared.Matches(text));
            var patterns = names.Length == 0 ? shapes : [.. shapes, $@"\b(?:{names})\s*[?!]?\s*\.values?\b"];
            var read = new Regex(string.Join("|", patterns), RegexOptions.CultureInvariant);
            foreach (Match match in read.Matches(text)) {
                int line = text.AsSpan(0, match.Index).Count('\n') + 1;
                reads.Add($"{path}:{line}: a view reads a read-model object's whole record ({match.Value.Trim()}), "
                    + "so a change to any field redraws it; read the fields it shows.");
            }
        }
        return reads;
    }

    /// The distinct `name` groups of `matches` as regular expression alternatives.
    private static string Alternatives(IEnumerable<Match> matches) =>
        string.Join("|", matches.Select(match => match.Groups["name"].Value).Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal).Select(Regex.Escape));

